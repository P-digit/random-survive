def _with_distance(lat, lon, items):
    return sorted(({**c, "km": geo.haversine_km(lat, lon, c["lat"], c["lon"])} for c in items),
                  key=lambda c: c["km"])


def nearest_city(lat, lon, max_km=None, country=None, airport=None, mission=None):
    """조건에 맞는 가장 가까운 도시. 같은 나라를 먼저 찾고, 없으면 나라와 상관없이 찾는다. 없으면 None."""
    pool = [c for c in CITY_LIST
            if (airport is None or c["airport"] == airport) and (not mission or c["mission"])]
    for candidates in ([c for c in pool if country and c["country"] == country], pool):
        if not candidates:
            continue
        best = _with_distance(lat, lon, candidates)[0]
        if max_km is None or best["km"] <= max_km:
            return best
        if country and candidates is not pool:
            continue
    return None


